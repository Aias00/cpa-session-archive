import { expect, test } from '@playwright/test'
import { installScaleFixture, scaleSession } from './session-scale-fixture.js'

test('all matching bulk archive crosses pagination, protects edits and favorites, and undoes safely', async ({ page }) => {
  const initial = Array.from({ length: 1105 }, (_, index) => scaleSession(index))
  initial[0].management.starred = true
  initial[1].management.title = 'Manually reviewed title'; initial[1].manuallyEdited = true
  const fixture = await installScaleFixture(page, initial)
  await expect(page.locator('#resultCount')).toHaveText('1,105 个会话')
  await expect(page.locator('#rows tr')).toHaveCount(100)
  await page.locator('#sessionBulkOpen').click()
  await page.locator('#bulkArchive').selectOption('true')
  await page.locator('#sessionBulkPreview').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('预览，尚未执行')
  await expect(page.locator('#bulkAcknowledgeScope')).toHaveCount(0)
  expect(fixture.sessions.filter((item) => item.management.archived)).toHaveLength(0)
  const plan = [...fixture.plans.values()][0]
  expect(plan.job.total).toBe(1105); expect(plan.job.protected).toBe(2)
  fixture.sessions[2].management.revision++
  fixture.sessions[2].management.note = 'Changed after preview'
  await page.locator('#sessionBulkApply').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('处理完成')
  expect(fixture.requests.filter((item) => item.path === 'session-bulk-apply')).toHaveLength(12)
  expect(fixture.sessions.filter((item) => item.management.archived)).toHaveLength(1102)
  expect(fixture.sessions[1].management.title).toBe('Manually reviewed title')
  expect(plan.job.conflicts).toBe(1)
  fixture.sessions[3].management.revision++
  fixture.sessions[3].management.note = 'Keep post-archive manual edit'
  await page.locator('#sessionBulkUndo').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('撤销结束')
  expect(plan.job.undo_conflicts).toBe(1)
  expect(fixture.sessions.filter((item) => item.management.archived)).toHaveLength(1)
  expect(fixture.sessions[3].management.note).toBe('Keep post-archive manual edit')
})

test('paused partial jobs recover after reload; undo cancels the frozen pending set', async ({ page }) => {
  const fixture = await installScaleFixture(page, Array.from({ length: 250 }, (_, index) => scaleSession(index)))
  await expect(page.locator('#resultCount')).toHaveText('250 个会话')
  await page.locator('#sessionBulkOpen').click()
  await page.locator('#bulkAddTags').fill('reviewed')
  await page.locator('#sessionBulkPreview').click()
  const hold = fixture.holdNextChunk()
  await page.locator('#sessionBulkApply').click()
  await hold.reached
  await page.locator('#sessionBulkPause').click()
  hold.release()
  await expect(page.locator('#sessionBulkApply')).toBeEnabled()
  expect(fixture.sessions.filter((item) => item.management.tags.includes('reviewed'))).toHaveLength(100)
  expect(fixture.requests.filter((item) => item.path === 'session-bulk-apply')).toHaveLength(1)
  await page.reload()
  await page.locator('#sessionBulkOpen').click()
  await page.getByRole('button', { name: /执行中／可继续 · 250/ }).click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('执行中／可继续')
  await page.locator('#sessionBulkUndo').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('撤销结束')
  const plan = [...fixture.plans.values()][0]
  expect(plan.job.undone).toBe(100); expect(plan.job.cancelled).toBe(150)
  expect(fixture.sessions.filter((item) => item.management.tags.includes('reviewed'))).toHaveLength(0)
  expect(fixture.sessions.every((item) => item.management.tags.includes('existing'))).toBe(true)
})

test('ambiguous write stops requests until explicit status refresh and resume', async ({ page }) => {
  const fixture = await installScaleFixture(page, Array.from({ length: 225 }, (_, index) => scaleSession(index)))
  await expect(page.locator('#resultCount')).toHaveText('225 个会话')
  await page.locator('#sessionBulkOpen').click()
  await page.locator('#bulkAddTags').fill('triaged')
  await page.locator('#sessionBulkPreview').click()
  fixture.ambiguousNext()
  await page.locator('#sessionBulkApply').click()
  await expect(page.locator('#sessionBulkError')).toContainText('已停止后续请求')
  await expect(page.locator('#sessionBulkApply')).toBeDisabled()
  expect(fixture.requests.filter((item) => item.path === 'session-bulk-apply')).toHaveLength(1)
  await page.locator('#sessionBulkRefresh').click()
  await expect(page.locator('#sessionBulkError')).toHaveCount(0)
  await expect(page.locator('#sessionBulkApply')).toBeEnabled()
  expect(fixture.requests.filter((item) => item.path === 'session-bulk-apply')).toHaveLength(1)
  await page.locator('#sessionBulkApply').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('处理完成')
  expect(fixture.requests.filter((item) => item.path === 'session-bulk-apply')).toHaveLength(3)
  expect(fixture.sessions.every((item) => item.management.tags.includes('triaged'))).toBe(true)
})

test('automatic views and exact project IDs stay scoped; stale previews require original-scope confirmation', async ({ page }) => {
  const fixture = await installScaleFixture(page, [scaleSession(0), scaleSession(1), scaleSession(2, { project: '/work/two/project', exactFacets: { 'project.id': 'project-two', 'project.path': '/work/two/project', client: 'codex' } }), scaleSession(3, { project: undefined, exactFacets: { client: 'codex' } })])
  await expect(page.locator('#resultCount')).toHaveText('4 个会话')
  await page.locator('#automaticView').selectOption('inactive')
  await expect(page.locator('#resultCount')).toHaveText('2 个会话')
  await expect(page.getByText('按最近活动时间分组；未活跃不代表任务已完成。')).toBeVisible()
  await page.locator('#inactiveDays').selectOption('180')
  await expect(page.locator('#resultCount')).toHaveText('0 个会话')
  await page.locator('#automaticView').selectOption('unassigned')
  await expect(page.locator('#resultCount')).toHaveText('1 个会话')
  await page.locator('#automaticView').selectOption('all')
  const navigation = page.getByRole('navigation', { name: '项目筛选' })
  await navigation.locator('button[title="project.id: project-two"]').click()
  await expect(page.locator('#resultCount')).toHaveText('1 个会话')
  await page.locator('#sessionBulkOpen').click()
  await page.locator('#bulkAddTags').fill('project-only')
  await page.locator('#sessionBulkPreview').click()
  await expect(page.locator('#sessionBulkFrozenScope')).toContainText('project.id=project-two')
  await page.keyboard.press('Escape')
  await navigation.getByRole('button', { name: '所有项目', exact: true }).click()
  await expect(page.locator('#resultCount')).toHaveText('4 个会话')
  await page.locator('#sessionBulkOpen').click()
  await expect(page.locator('#sessionBulkApply')).toBeDisabled()
  await page.locator('#bulkAcknowledgeScope').check()
  await page.locator('#sessionBulkApply').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('处理完成')
  expect(fixture.sessions.filter((item) => item.management.tags.includes('project-only')).map((item) => item.session_id)).toEqual(['scale-session-2'])
  expect(fixture.queries.some((query) => query.get('project.id') === 'project-two')).toBe(true)
})

test('explicit protection opt-ins can archive every row while recovery and undo remain reachable', async ({ page }) => {
  const initial = Array.from({ length: 3 }, (_, index) => scaleSession(index))
  initial[0].management.starred = true
  initial[1].manuallyEdited = true; initial[1].management.note = 'Preserved manual notes'
  const fixture = await installScaleFixture(page, initial)
  await expect(page.locator('#resultCount')).toHaveText('3 个会话')
  await page.locator('#sessionBulkOpen').click()
  await page.locator('#bulkArchive').selectOption('true')
  await page.locator('#bulkIncludeStarred').check()
  await page.locator('#bulkIncludeEdited').check()
  await page.locator('#sessionBulkPreview').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('预览，尚未执行')
  expect([...fixture.plans.values()][0].job.protected).toBe(0)
  await page.locator('#sessionBulkApply').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('处理完成')
  await page.keyboard.press('Escape')
  await expect(page.locator('#resultCount')).toHaveText('0 个会话')
  await expect(page.locator('#sessionBulkOpen')).toBeEnabled()
  await page.reload()
  await page.locator('#sessionBulkOpen').click()
  await expect(page.locator('#sessionBulkPreview')).toBeDisabled()
  await page.getByRole('button', { name: /处理完成 · 3 · 归档/ }).click()
  await page.locator('#sessionBulkUndo').click()
  await expect(page.locator('#sessionBulkStatus')).toHaveText('撤销结束')
  await page.keyboard.press('Escape')
  await expect(page.locator('#resultCount')).toHaveText('3 个会话')
  expect(fixture.sessions[0].management.starred).toBe(true)
  expect(fixture.sessions[1].management.note).toBe('Preserved manual notes')
})
